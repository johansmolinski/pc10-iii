// tb_intfd.sv - the FDC card with drive B: behind fdd_intdrv.sv (the image
// backend for A:/B: and the real drive are C++ models in intfd_run.cpp).
//
// GPL-3.0-or-later, pc10-iii.

module tb_intfd (
    input  logic        clk,
    input  logic        reset,
    input  logic        pc_reset,
    input  logic        enable,

    // card bus
    input  logic [19:0] isa_addr,
    input  logic [7:0]  isa_dout,
    output logic [7:0]  isa_din,
    output logic        isa_dsel,
    input  logic        isa_ior_n,
    input  logic        isa_iow_n,
    input  logic        isa_aen,
    output logic [7:2]  isa_irq,
    output logic [3:1]  isa_drq,
    input  logic [3:0]  isa_dack_n,
    input  logic        isa_tc,

    // the image backend (A:, and B: with enable = 0)
    input  logic [1:0]  i_drv_80trk,
    input  logic [1:0]  i_img_present,
    input  logic [1:0]  i_img_wp,
    input  logic [15:0] i_img_tracks,
    input  logic [3:0]  i_img_heads,
    input  logic [11:0] i_img_spt,
    output logic        i_sp_req,
    output logic        sp_write,
    output logic        sp_fmt,
    output logic        sp_drive,
    output logic [7:0]  sp_cyl,
    output logic        sp_head,
    output logic [7:0]  sp_sector,
    output logic [15:0] sp_lba,
    input  logic        i_sp_rd_valid,
    input  logic [7:0]  i_sp_rd_data,
    output logic        sp_wr_valid,
    output logic [7:0]  sp_wr_data,
    input  logic        i_sp_wr_ready,
    input  logic        i_sp_done,
    input  logic        i_sp_err,

    // the card's view
    output logic [1:0]  drv_select,
    output logic [1:0]  drv_motor,
    output logic        drv_step,
    output logic        drv_step_in,
    output logic        fdc_active,
    output logic [1:0]  img_present,
    output logic [1:0]  img_wp,

    // the drive
    output logic        f_motor_n,
    output logic        f_select_n,
    output logic        f_stepdir_n,
    output logic        f_step_n,
    output logic        f_side1_n,
    output logic        f_wdata_n,
    output logic        f_wgate_n,
    input  logic        f_index_n,
    input  logic        f_track0_n,
    input  logic        f_wpt_n,
    input  logic        f_rdata_n,
    output logic        busy,
    output logic [6:0]  cyl,
    output logic        known
);

logic [1:0]  drv_80trk;
logic [15:0] img_tracks;
logic [3:0]  img_heads;
logic [11:0] img_spt;
logic        sp_req, sp_rd_valid, sp_wr_ready, sp_done, sp_err;
logic [7:0]  sp_rd_data;
logic        isa_ready;

fdc_card u_fdc (
    .clk         (clk),
    .reset       (reset || pc_reset),
    .isa_addr    (isa_addr),
    .isa_addr_next (20'd0),
    .isa_aen_next  (1'b0),
    .isa_ior_n_next(1'b1),
    .isa_iow_n_next(1'b1),
    .isa_dout    (isa_dout),
    .isa_din     (isa_din),
    .isa_dsel    (isa_dsel),
    .isa_ior_n   (isa_ior_n),
    .isa_iow_n   (isa_iow_n),
    .isa_aen     (isa_aen),
    .isa_ready   (isa_ready),
    .isa_irq     (isa_irq),
    .isa_drq     (isa_drq),
    .isa_dack_n  (isa_dack_n),
    .isa_tc      (isa_tc),
    .drv_80trk   (drv_80trk),
    .img_present (img_present),
    .img_wp      (img_wp),
    .img_tracks  (img_tracks),
    .img_heads   (img_heads),
    .img_spt     (img_spt),
    .drv_motor   (drv_motor),
    .fdc_active  (fdc_active),
    .drv_select  (drv_select),
    .drv_step    (drv_step),
    .drv_step_in (drv_step_in),
    .sp_req      (sp_req),
    .sp_write    (sp_write),
    .sp_fmt      (sp_fmt),
    .sp_drive    (sp_drive),
    .sp_cyl      (sp_cyl),
    .sp_head     (sp_head),
    .sp_sector   (sp_sector),
    .sp_lba      (sp_lba),
    .sp_rd_valid (sp_rd_valid),
    .sp_rd_data  (sp_rd_data),
    .sp_wr_valid (sp_wr_valid),
    .sp_wr_data  (sp_wr_data),
    .sp_wr_ready (sp_wr_ready),
    .sp_done     (sp_done),
    .sp_err      (sp_err)
);

fdd_intdrv u_intdrv (
    .clk          (clk),
    .reset        (reset),
    .pc_reset     (pc_reset),
    .enable       (enable),
    .drv_80trk    (drv_80trk),
    .img_present  (img_present),
    .img_wp       (img_wp),
    .img_tracks   (img_tracks),
    .img_heads    (img_heads),
    .img_spt      (img_spt),
    .drv_motor    (drv_motor),
    .drv_select   (drv_select),
    .drv_step     (drv_step),
    .drv_step_in  (drv_step_in),
    .fdc_active   (fdc_active),
    .sp_req       (sp_req),
    .sp_write     (sp_write),
    .sp_fmt       (sp_fmt),
    .sp_drive     (sp_drive),
    .sp_cyl       (sp_cyl),
    .sp_head      (sp_head),
    .sp_sector    (sp_sector),
    .sp_rd_valid  (sp_rd_valid),
    .sp_rd_data   (sp_rd_data),
    .sp_wr_valid  (sp_wr_valid),
    .sp_wr_ready  (sp_wr_ready),
    .sp_wr_data   (sp_wr_data),
    .sp_done      (sp_done),
    .sp_err       (sp_err),
    .i_drv_80trk  (i_drv_80trk),
    .i_img_present(i_img_present),
    .i_img_wp     (i_img_wp),
    .i_img_tracks (i_img_tracks),
    .i_img_heads  (i_img_heads),
    .i_img_spt    (i_img_spt),
    .i_sp_req     (i_sp_req),
    .i_sp_rd_valid(i_sp_rd_valid),
    .i_sp_rd_data (i_sp_rd_data),
    .i_sp_wr_ready(i_sp_wr_ready),
    .i_sp_done    (i_sp_done),
    .i_sp_err     (i_sp_err),
    .f_motor_n    (f_motor_n),
    .f_select_n   (f_select_n),
    .f_stepdir_n  (f_stepdir_n),
    .f_step_n     (f_step_n),
    .f_side1_n    (f_side1_n),
    .f_wdata_n    (f_wdata_n),
    .f_wgate_n    (f_wgate_n),
    .f_index_n    (f_index_n),
    .f_track0_n   (f_track0_n),
    .f_wpt_n      (f_wpt_n),
    .f_rdata_n    (f_rdata_n),
    .busy         (busy),
    .cyl          (cyl),
    .known        (known)
);

endmodule
