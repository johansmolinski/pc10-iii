#!/usr/bin/env python3
"""Run headless MartyPC (benchmark mode + CPU trace) in a fresh run directory.

Runs on the build host (fedora). Called by run_ref.sh; usable on its own:

    remote_run.py --marty DIR --bios FILE --cycles N --out RUNDIR
                  [--mode CycleText|Instruction] [--no-refresh] [--no-wait-states]
                  [--cga-clock Cycle|Dynamic|Character|Default] [--ram-kb 640]

DIR is a MartyPC source tree built with tools/martypc/headless-trace.patch
(target/release/martypc_headless). The run directory gets its own
martypc.toml (derived from DIR/install/martypc.toml), one machine
definition (pc10_ref: IBM 5160, CGA, keyboard, no FDC/HDC/serial) and one
ROM set (the given BIOS at F000:E000 for 8 KB images, F000:0000 for 64 KB).
The trace lands in RUNDIR/output/traces/<mode>.log.
"""
import argparse
import os
import re
import shutil
import subprocess
import sys

MACHINE = """# pc10-iii reference machine (generated by tools/martypc/remote_run.py)
[[machine]]
name = "pc10_ref"
type = "Ibm5160"
rom_set = "pc10_bios"
speaker = true
ppi_turbo = false

    [machine.memory]
    conventional.size = 0x{ram:X}
    conventional.wait_states = 0

    [[machine.video]]
    bus_type = "ISA"
    type = "CGA"
    clock_mode = "{cga_clock}"

    [machine.keyboard]
    type = "ModelF"
    layout = "US"
"""

ROMDEF = """# pc10-iii reference BIOS (generated by tools/martypc/remote_run.py)
[[romset]]
alias = "pc10_bios"
desc = "pc10-iii reference BIOS ({name})"
priority = 100
provides = ["bios", "ibm5160", "expansion"]
rom = [
    {{ filename = "{name}", addr = 0x{addr:X}, size = {size}, chip = "bios" }}
]
"""


def set_key(text, section, key, value):
    """Set key = value inside [section] of a TOML text (first occurrence,
    commented or not). Appends the key to the section if it is missing."""
    lines = text.split("\n")
    cur = None
    sec_start = None
    done = False
    pat = re.compile(r"^\s*#?\s*" + re.escape(key) + r"\s*=")
    for i, line in enumerate(lines):
        m = re.match(r"^\s*\[+([^\]]+)\]+\s*$", line)
        if m:
            if cur == section:
                break
            cur = m.group(1).strip()
            if cur == section:
                sec_start = i
            continue
        if cur == section and pat.match(line):
            if not done:
                lines[i] = f"{key} = {value}"
                done = True
            elif not line.lstrip().startswith("#"):
                lines[i] = "# (pc10-iii) " + line   # drop a later duplicate
    if done:
        return "\n".join(lines)
    if sec_start is None:
        raise SystemExit(f"section [{section}] not in martypc.toml")
    lines.insert(sec_start + 1, f"{key} = {value}")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--marty", required=True)
    ap.add_argument("--bios", required=True)
    ap.add_argument("--cycles", type=int, required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--mode", default="CycleText", choices=["CycleText", "Instruction"])
    ap.add_argument("--no-refresh", action="store_true")
    ap.add_argument("--no-wait-states", action="store_true")
    ap.add_argument("--cga-clock", default="Cycle")
    ap.add_argument("--ram-kb", type=int, default=640)
    a = ap.parse_args()

    marty = os.path.abspath(a.marty)
    exe = os.path.join(marty, "target/release/martypc_headless")
    out = os.path.abspath(a.out)
    if os.path.exists(out):
        shutil.rmtree(out)
    for d in ("assets", "configs/machines", "configs/rom_definitions", "media/roms", "media/hdds",
              "media/floppies", "output/traces"):
        os.makedirs(os.path.join(out, d))
    shutil.copytree(os.path.join(marty, "install/configs/keyboard_layouts"),
                    os.path.join(out, "configs/keyboard_layouts"))

    bios = open(a.bios, "rb").read()
    size = len(bios)
    if size not in (8192, 16384, 32768, 65536):
        raise SystemExit(f"BIOS size {size} not 8/16/32/64 KB")
    name = "pc10_bios.rom"
    open(os.path.join(out, "media/roms", name), "wb").write(bios)
    with open(os.path.join(out, "configs/rom_definitions/romdef_pc10.toml"), "w") as f:
        f.write(ROMDEF.format(name=name, addr=0x100000 - size, size=size))
    with open(os.path.join(out, "configs/machines/pc10_ref.toml"), "w") as f:
        f.write(MACHINE.format(ram=a.ram_kb * 1024, cga_clock=a.cga_clock))

    t = open(os.path.join(marty, "install/martypc.toml")).read()
    edits = [
        ("machine", "config_name", '"pc10_ref"'),
        ("machine", "prefer_oem", "false"),
        ("machine", "patch_roms", "false"),
        ("machine", "custom_roms", "true"),
        ("machine", "turbo", "false"),
        ("machine", "pit_phase", "0"),
        ("machine.cpu", "dram_refresh_simulation", "false" if a.no_refresh else "true"),
        ("machine.cpu", "wait_states", "false" if a.no_wait_states else "true"),
        ("machine.cpu", "off_rails_detection", "false"),
        ("machine.cpu", "on_halt", '"Continue"'),
        ("machine.cpu", "instruction_history", "false"),
        ("machine.cpu", "trace_on", "true"),
        ("machine.cpu", "trace_mode", f'"{a.mode}"'),
        ("machine.cpu", "trace_file", f'"{a.mode}.log"'),
        ("emulator", "basedir", '"."'),
        ("emulator", "benchmark_mode", "true"),
        ("emulator", "headless", "true"),
        ("emulator.benchmark", "config_name", '"pc10_ref"'),
        ("emulator.benchmark", "config_overlays", "[]"),
        ("emulator.benchmark", "prefer_oem", "false"),
        ("emulator.benchmark", "end_condition", '"Cycles"'),
        ("emulator.benchmark", "cycles", str(a.cycles)),
    ]
    for sec, key, val in edits:
        t = set_key(t, sec, key, val)
    open(os.path.join(out, "martypc.toml"), "w").write(t)

    with open(os.path.join(out, "run.log"), "w") as log:
        log.write("cmd: cd %s && %s\n" % (out, exe))
        log.flush()
        env = dict(os.environ, RUST_LOG=os.environ.get("RUST_LOG", "warn"))
        r = subprocess.run([exe], cwd=out, stdout=log, stderr=subprocess.STDOUT, env=env)
    sys.stdout.write(open(os.path.join(out, "run.log")).read())
    if r.returncode != 0:
        raise SystemExit(f"martypc_headless exited with {r.returncode}")


if __name__ == "__main__":
    main()
