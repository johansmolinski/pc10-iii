#!/usr/bin/env bash
##############################################################################
# PC10-III for MEGA65: build the QNICE firmware (m2m-rom.rom)
#
# Called by the Vivado pre-synthesis hook (synth_pre.tcl) and by build_all.sh.
# Based on Megamiga's CORE/m2m-rom/make_rom.sh (rodata and code banks dropped:
# this firmware fits the 32K-word ROM).
#
#   1. builds the QNICE assembler (qasm, qasm2rom) for this machine into .tools/
#      (from M2M/QNICE/assembler, so the submodule stays clean)
#   2. refreshes M2M/QNICE/dist_kit/sysdef.asm from the monitor's sysdef.asm
#   3. generates osm_const.asm (C_MENU_* of mega65.vhd -> PC_OSM_*, the core's
#      OPTM_G_* of config.vhd -> PC_OPTM_G_*, C_DEV_PC_* of globals.vhd ->
#      PC_DEV_*), globals.asm, shell_fhandles.asm, shell_fh_ptrs.asm
#   4. assembles m2m-rom.asm, trims the RAM variables off the image and checks
#      the 32768-word ROM limit (M2M-UPSTREAM rom-32k: 0x8000 is the device
#      window) against the END_OF_ROM marker
##############################################################################

set -u
cd "$(dirname "$0")"

QA=../../M2M/QNICE/assembler
T=.tools
mkdir -p "$T"
CC=$(command -v cc || command -v gcc)
if [ ! -x "$T/qasm" ] || [ "$QA/qasm.c" -nt "$T/qasm" ]; then
    "$CC" -O2 -w -o "$T/qasm" "$QA/qasm.c" || { echo "ERROR: cannot build qasm"; exit 1; }
fi
if [ ! -x "$T/qasm2rom" ] || [ "$QA/qasm2rom.c" -nt "$T/qasm2rom" ]; then
    "$CC" -O2 -w -o "$T/qasm2rom" "$QA/qasm2rom.c" || { echo "ERROR: cannot build qasm2rom"; exit 1; }
fi

cp ../../M2M/QNICE/monitor/sysdef.asm ../../M2M/QNICE/dist_kit/sysdef.asm

##############################################################################
# osm_const.asm
##############################################################################

{
    echo "; DO NOT MANUALLY EDIT"
    echo "; AUTOGENERATED BY ./make_rom.sh from ../vhdl/mega65.vhd, config.vhd, globals.vhd"
    echo ""
    awk '/constant C_MENU_/ {gsub("C_MENU_", "PC_OSM_"); gsub(";", ""); printf("%-31s .EQU %s\n", $2, $6)}' ../vhdl/mega65.vhd
    awk '/constant OPTM_G_/ && !/16#/ {gsub("OPTM_G_", "PC_OPTM_G_"); gsub(";", ""); printf("%-31s .EQU %s\n", $2, $6)}' ../vhdl/config.vhd
    awk '/constant C_DEV_PC_/ {name=$2; sub(/^C_DEV_PC_/, "", name); gsub(/.*x"/, ""); gsub(/".*/, ""); printf("%-31s .EQU 0x%s\n", "PC_DEV_" name, $0)}' ../vhdl/globals.vhd
} > osm_const.asm

##############################################################################
# M2M framework: globals.asm, shell_fhandles.asm, shell_fh_ptrs.asm
##############################################################################

{
    echo "; DO NOT MANUALLY EDIT"
    echo "; AUTOGENERATED BY ./make_rom.sh"
    echo "; These constants are taken from ../vhdl/globals.vhd"
    echo ""
} > globals.asm

awk '/constant C_VDNUM/ {gsub(/.*:=|;.*/, "", $0); split($0, a, " "); val=a[1]; if (val+0 == 0) val=1; printf("VDRIVES_MAX                 .EQU %s\n", val)}' ../vhdl/globals.vhd >> globals.asm
awk '/constant C_CRTROMS_MAN_NUM/ {gsub(/.*:=|;.*/, "", $0); split($0, a, " "); val=a[1]; if (val+0 == 0) val=1; printf("CRTROM_MAN_MAX              .EQU %s\n", val)}' ../vhdl/globals.vhd >> globals.asm
awk '/constant C_CRTROMS_AUTO_NUM/ {gsub(/.*:=|;.*/, "", $0); split($0, a, " "); val=a[1]; if (val+0 == 0) val=1; printf("CRTROM_AUT_MAX              .EQU %s\n", val)}' ../vhdl/globals.vhd >> globals.asm

vdrives_max=$(awk '/constant C_VDNUM/ {gsub(/.*:=|;.*/, "", $0); split($0, a, " "); print a[1]}' ../vhdl/globals.vhd)
crtrom_man_max=$(awk '/constant C_CRTROMS_MAN_NUM/ {gsub(/.*:=|;.*/, "", $0); split($0, a, " "); print a[1]}' ../vhdl/globals.vhd)
if [ "$vdrives_max" -eq 0 ]; then vdrives_max=1; fi
if [ "$crtrom_man_max" -eq 0 ]; then crtrom_man_max=1; fi

{
    echo "; DO NOT MANUALLY EDIT"
    echo "; AUTOGENERATED BY ./make_rom.sh"
    echo ""
    for ((i=1; i<=vdrives_max; i++)); do echo "HANDLE_VD_FILE$i    .BLOCK  FAT32\$FDH_STRUCT_SIZE"; done
    for ((i=1; i<=crtrom_man_max; i++)); do echo "HANDLE_RM_FILE$i    .BLOCK  FAT32\$FDH_STRUCT_SIZE"; done
} > shell_fhandles.asm

{
    echo "; DO NOT MANUALLY EDIT"
    echo "; AUTOGENERATED BY ./make_rom.sh"
    echo ""
} > shell_fh_ptrs.asm
print_file_handles() {
    local label=$1 pointer_name=$2 count=$3
    printf "%-20s .DW  " "$label" >> shell_fh_ptrs.asm
    for ((i=1;i<=count;i++)); do
        printf "%s%d" "$pointer_name" $i >> shell_fh_ptrs.asm
        if (( i % 3 == 0 && i < count )); then
            printf ",\n%-20s .DW  " " " >> shell_fh_ptrs.asm
        elif (( i % 3 != 0 && i < count )); then
            printf ", " >> shell_fh_ptrs.asm
        fi
    done
    printf "\n" >> shell_fh_ptrs.asm
}
print_file_handles "HNDL_VD_FILES" "HANDLE_VD_FILE" $vdrives_max
print_file_handles "HNDL_RM_FILES" "HANDLE_RM_FILE" $crtrom_man_max

##############################################################################
# Assemble: m2m-rom.out (records), m2m-rom.lis (listing), m2m-rom.rom (image)
##############################################################################

rm -f m2m-rom.out m2m-rom.rom m2m-rom.lis
"$CC" -xc -E m2m-rom.asm 2>/dev/null | sed '/^#.*/d' > __m2m_rom__.asm
"$T/qasm" __m2m_rom__.asm m2m-rom.out m2m-rom.lis > asm.log 2>&1
ASM_RC=$?
rm -f __m2m_rom__.asm
if [ "$ASM_RC" -ne 0 ] || [ ! -f m2m-rom.out ]; then
    cat asm.log
    echo "ERROR: assembling m2m-rom.asm failed (qasm exit ${ASM_RC})."
    exit 1
fi
"$T/qasm2rom" m2m-rom.out m2m-rom.rom > /dev/null || { echo "ERROR: qasm2rom failed"; exit 1; }

##############################################################################
# Trim the variables off the image and guard the ROM budget (Megamiga's
# make_rom.sh: line N of the .out/.rom pair is the word at address N-1 as long
# as the addresses are contiguous from 0; everything after that must be RAM,
# address >= 0xA000; the END_OF_ROM marker must agree)
##############################################################################

ROM_MAX_WORDS=32768

if ! ROM_WORDS=$(awk '
function hex(s,   i, c, v, d) {
    v = 0; s = toupper(s); sub(/^0X/, "", s)
    for (i = 1; i <= length(s); i++) {
        c = substr(s, i, 1); d = index("0123456789ABCDEF", c) - 1
        if (d < 0) return -1
        v = v * 16 + d
    }
    return v
}
{ sub(/\r$/, "") }
{
    a = hex($1)
    if (a < 0)                { err = "unparsable address in line " NR ": " $1; exit 1 }
    if (!done && a == NR - 1) { n = NR; next }
    done = 1
    if (a < 40960)            { err = "address " $1 " (line " NR ") is outside the ROM image and below the RAM (0xA000)"; exit 1 }
}
END {
    if (err != "")  { print "ERROR: m2m-rom.out cannot be trimmed: " err; exit 1 }
    if (n + 0 == 0) { print "ERROR: m2m-rom.out contains no ROM words."; exit 1 }
    print n + 0
}' m2m-rom.out); then
    echo "$ROM_WORDS"
    exit 1
fi

EOR_ADDR=$(awk '
{ sub(/\r$/, "") }
/^Label-list:/ { inlist = 1; next }
inlist {
    line = $0
    gsub(/:/, " ", line)
    n = split(line, t, /[ \t]+/)
    for (i = 1; i < n; i++)
        if (t[i] == "END_OF_ROM") { print t[i + 1]; exit }
}' m2m-rom.lis)

case "$EOR_ADDR" in
    0x[0-9A-Fa-f]*) ;;
    *)  echo "ERROR: END_OF_ROM not found in the label list of m2m-rom.lis."; exit 1 ;;
esac
EOR_WORDS=$(( EOR_ADDR + 1 ))
if [ "$EOR_WORDS" -ne "$ROM_WORDS" ]; then
    echo "ERROR: the ROM image is ${ROM_WORDS} words but END_OF_ROM (${EOR_ADDR}) says ${EOR_WORDS}."
    exit 1
fi

head -n "$ROM_WORDS" m2m-rom.rom > m2m-rom.rom.tmp && mv m2m-rom.rom.tmp m2m-rom.rom

if [ "$ROM_WORDS" -gt "$ROM_MAX_WORDS" ]; then
    echo "ERROR: m2m-rom.rom is ${ROM_WORDS} words, exceeds the ${ROM_MAX_WORDS}-word Shell-ROM budget."
    exit 1
fi
echo "Shell ROM: ${ROM_WORDS}/${ROM_MAX_WORDS} words."
